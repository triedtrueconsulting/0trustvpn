#!/usr/bin/env bash
# ============================================================================
# Regenerate the self-hosted brand faces in web/fonts/
# ============================================================================
# The site used to link fonts.googleapis.com. On /surf that is a contradiction:
# the page's whole pitch is that your visit does not get handed to a third
# party, and the first thing it did was ask Google for a font. Self-hosting
# also removes a render-blocking round trip on the funnel's front door.
#
# Only the latin and latin-ext subsets are kept. They cover every accented
# character the site and the warrant canary actually use (Zürich, BÜPF, Sàrl);
# Cyrillic, Greek and Vietnamese are not.
#
#   ./scripts/fetch-fonts.sh          # rewrite web/fonts/ from upstream
# ============================================================================
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_DIR/web/fonts"
UA='Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36'
URL='https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=JetBrains+Mono:wght@400;500;700&family=IBM+Plex+Sans:wght@300;400;500;600&display=swap'

mkdir -p "$OUT"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -fsS -A "$UA" "$URL" -o "$tmp/src.css"

OUT="$OUT" python3 - "$tmp/src.css" <<'PY'
import os, re, subprocess, sys
css = open(sys.argv[1]).read()
out = os.environ["OUT"]
blocks = re.findall(r'/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})', css)
keep, files = [], []
for subset, block in blocks:
    if subset not in ("latin", "latin-ext"):
        continue
    fam = re.search(r"font-family: *'([^']+)'", block).group(1)
    wt = re.search(r"font-weight: *(\d+)", block).group(1)
    sty = re.search(r"font-style: *(\w+)", block).group(1)
    url = re.search(r"url\((https://[^)]+)\)", block).group(1)
    name = f"{fam.lower().replace(' ', '-')}-{wt}{'-italic' if sty == 'italic' else ''}-{subset}.woff2"
    files.append((url, name))
    keep.append(re.sub(r"url\(https://[^)]+\)", f"url(/fonts/{name})", block))
open(os.path.join(out, "faces.css"), "w").write(
    "/* Self-hosted brand faces. Generated by scripts/fetch-fonts.sh from\n"
    "   Google's css2 output, latin and latin-ext subsets only. Do not edit.\n"
    "   Self-hosted on purpose: /surf promises your visit is not handed to a\n"
    "   third party, and a webfont request to one is exactly that. */\n"
    + "\n".join(keep) + "\n")
for url, name in files:
    subprocess.run(["curl", "-fsS", "-o", os.path.join(out, name), url], check=True)
print(f"wrote {len(files)} faces + faces.css")
PY
