#!/usr/bin/env bash
# ============================================================================
# Vendor third-party JS for the landing page
# ============================================================================
# We deliberately don't load anything from CDNs in production. This script
# downloads pinned third-party JS from upstream, verifies its SHA-256 against
# a manifest, and stages it in web/vendor/ for the operator to commit.
#
# Run on a workstation with network access. The produced files are then
# committed to git and served from the same domain as everything else.
#
# Usage:
#   ./scripts/vendor-third-party.sh                 # fetch + verify
#   ./scripts/vendor-third-party.sh --check-only    # verify only, don't fetch
# ============================================================================
set -euo pipefail

log()  { printf '\033[1;33m[+] %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m[✓] %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m[!] %s\033[0m\n' "$*" >&2; exit 1; }

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR_DIR="$REPO_DIR/web/vendor"
MANIFEST="$REPO_DIR/web/vendor/MANIFEST.txt"

check_only=0
[[ "${1:-}" == "--check-only" ]] && check_only=1

# ----------------------------------------------------------------------------
# Pinned dependencies — one line per asset.
#
# Format:   <name>|<url>|<sha256>
#
# To update an entry: bump the commit hash in the URL, fetch the file,
# compute its sha256, paste both into this table, and review the diff.
# ----------------------------------------------------------------------------
DEPS=(
  "qrcode.min.js|https://raw.githubusercontent.com/davidshimjs/qrcodejs/04f46c6a0708418cb7b96fc563eacae0fbf77674/qrcode.min.js|c541ef06327885a8415bca8df6071e14189b4855336def4f36db54bde8484f36"
)

mkdir -p "$VENDOR_DIR"

# Always write a fresh MANIFEST.txt so the running site can serve it as a
# transparency artifact (operator can publish it next to the JS itself).
{
    echo "# 0trust web/vendor/ pinned third-party assets"
    echo "# Generated by scripts/vendor-third-party.sh"
    echo "#"
    echo "# Each line: filename  sha256  source_url"
    echo "# Verify with: sha256sum -c <(awk '{print \$2, \" \", \$1}' MANIFEST.txt)"
    echo ""
    for dep in "${DEPS[@]}"; do
        IFS='|' read -r name url want_sha <<<"$dep"
        printf "%s  %s  %s\n" "$name" "$want_sha" "$url"
    done
} > "$MANIFEST"

# ----------------------------------------------------------------------------
# Fetch + verify each dep
# ----------------------------------------------------------------------------
fail=0
for dep in "${DEPS[@]}"; do
    IFS='|' read -r name url want_sha <<<"$dep"
    out="$VENDOR_DIR/$name"

    if (( check_only )) && [[ ! -f "$out" ]]; then
        die "$name missing — run without --check-only first"
    fi

    if (( !check_only )) || [[ ! -f "$out" ]]; then
        log "Fetching $name"
        curl -fsSL --proto '=https' --tlsv1.2 -o "$out.tmp" "$url" \
            || die "download failed: $url"
    fi

    log "Verifying $name"
    got_sha=$(sha256sum "${out}.tmp" 2>/dev/null || sha256sum "$out")
    got_sha=${got_sha%% *}
    if [[ "$got_sha" != "$want_sha" ]]; then
        printf "    expected: %s\n    got:      %s\n" "$want_sha" "$got_sha" >&2
        rm -f "$out.tmp"
        die "checksum MISMATCH for $name — refusing to install"
    fi
    [[ -f "$out.tmp" ]] && mv "$out.tmp" "$out"
    ok "$name  ($want_sha)"
done

cat <<EOF

  Vendored ${#DEPS[@]} asset(s) to $VENDOR_DIR/
  Manifest: $MANIFEST

  Next:
    git add web/vendor/
    git commit -m 'vendor: pin third-party JS'

  Then redeploy. The site no longer touches cdnjs.cloudflare.com.
EOF
