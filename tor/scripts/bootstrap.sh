#!/usr/bin/env bash
# ============================================================================
# 0trust Tor onion service bootstrap
# ============================================================================
# Stands up a v3 onion service mirror of the 0trust landing site on the same
# host as nginx. The onion serves the SAME static content as the clearnet
# site — there's no separate API path, no separate database, nothing
# operationally to maintain. The point is just that customers can browse and
# sign up without their ISP / DNS resolver learning they visited us.
#
# What this script does:
#   1. Installs tor from the official Tor Project repo (not Ubuntu's old fork)
#   2. Creates /var/lib/tor/0trust-hs with secure ownership
#   3. Writes a minimal /etc/tor/torrc that defines our hidden service
#   4. Starts tor, waits for the hostname file to appear
#   5. Reads the generated .onion address
#   6. Writes nginx snippets that:
#        - Add Onion-Location header to the clearnet server block
#          (so Tor Browser users get auto-promoted to .onion)
#        - Define a separate server block listening on 127.0.0.1:8090
#          that serves the same /var/www/0trust over plain HTTP
#          (Tor itself provides the E2E encryption — no TLS layer needed)
#   7. Reloads nginx
#   8. Prints the .onion address (publish it widely so customers can find it)
#
# Run on the same host as nginx, as root.
#
# Why this is safe:
#   - The hidden-service private key NEVER leaves /var/lib/tor/0trust-hs.
#     This script doesn't read it, doesn't copy it, doesn't print it.
#     Back it up out-of-band if you want the onion to survive host loss.
#   - The onion port maps to 127.0.0.1:8090, NOT the public nginx port,
#     so it can't be reached except via Tor.
#   - We DON'T proxy /api/v1 through the onion. Customer auth tokens stay
#     on clearnet over TLS (separate pipe, separate threat model). The
#     onion serves marketing + docs + canary + download links only.
# ============================================================================
set -euo pipefail

log()  { printf '\033[1;33m[+] %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m[✓] %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m[!] %s\033[0m\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run as root"
command -v nginx >/dev/null || die "nginx not installed"
command -v systemctl >/dev/null || die "systemd required"

HS_DIR="/var/lib/tor/0trust-hs"
HS_NAME="${HS_NAME:-0trust onion mirror}"
ONION_LOCAL_PORT="${ONION_LOCAL_PORT:-8090}"
NGINX_SNIPPETS="${NGINX_SNIPPETS:-/etc/nginx/snippets}"

# ----------------------------------------------------------------------------
log "Installing tor (official Tor Project repo, not Ubuntu's fork)"
# ----------------------------------------------------------------------------
# Ubuntu's tor package can lag by months. The Tor Project's apt repo tracks
# the current stable release within hours of upstream tags.
apt-get update -qq
apt-get install -y -qq apt-transport-https curl gnupg lsb-release

if [[ ! -f /etc/apt/sources.list.d/tor.list ]]; then
    distro=$(lsb_release -cs)
    cat > /etc/apt/sources.list.d/tor.list <<EOF
deb     [signed-by=/usr/share/keyrings/tor-archive-keyring.gpg] https://deb.torproject.org/torproject.org $distro main
deb-src [signed-by=/usr/share/keyrings/tor-archive-keyring.gpg] https://deb.torproject.org/torproject.org $distro main
EOF
    curl -fsSL https://deb.torproject.org/torproject.org/A3C4F0F979CAA22CDBA8F512EE8CBC9E886DDD89.asc \
        | gpg --dearmor -o /usr/share/keyrings/tor-archive-keyring.gpg
fi

apt-get update -qq
apt-get install -y -qq tor deb.torproject.org-keyring

# ----------------------------------------------------------------------------
log "Creating hidden service directory"
# ----------------------------------------------------------------------------
# Tor INSISTS on owning this directory itself (perms 0700, owner debian-tor).
# If we get this wrong, tor refuses to start with a confusing error.
if [[ ! -d "$HS_DIR" ]]; then
    mkdir -p "$HS_DIR"
    chown debian-tor:debian-tor "$HS_DIR"
    chmod 0700 "$HS_DIR"
fi

# ----------------------------------------------------------------------------
log "Writing /etc/tor/torrc additions"
# ----------------------------------------------------------------------------
# Idempotent: we wrap our additions in markers so re-running this script
# doesn't duplicate them.
MARK_START="# >>> 0trust hidden service >>>"
MARK_END="# <<< 0trust hidden service <<<"

# Remove old block if present
if grep -qF "$MARK_START" /etc/tor/torrc 2>/dev/null; then
    sed -i "/$MARK_START/,/$MARK_END/d" /etc/tor/torrc
fi

cat >> /etc/tor/torrc <<EOF

$MARK_START
# Auto-generated by tor/scripts/bootstrap.sh — do not edit between markers.
# Re-run the script if you need to change these settings.

# Use v3 onions (the default since Tor 0.4.6 deprecated v2)
HiddenServiceDir $HS_DIR/
HiddenServiceVersion 3

# Single-hop service. We deliberately use a full 3-hop circuit because:
#   - The site this serves is low-volume / non-real-time;
#   - Three hops protect us from being correlated with our hosting provider;
#   - We're not optimizing for latency on a marketing site.
HiddenServiceSingleHopMode 0
HiddenServiceNonAnonymousMode 0

# Port mapping: external port 80 on the onion -> local port $ONION_LOCAL_PORT
# Tor terminates the encryption; nginx serves plain HTTP on 127.0.0.1.
HiddenServicePort 80 127.0.0.1:$ONION_LOCAL_PORT

# We don't run an exit node from this host
ExitRelay 0

# Don't log the IP of clients connecting to the introduction points.
# (Tor's default is already privacy-friendly; we make it explicit.)
SafeLogging 1
$MARK_END
EOF

# ----------------------------------------------------------------------------
log "Starting tor and waiting for the .onion to be generated"
# ----------------------------------------------------------------------------
systemctl enable tor >/dev/null
systemctl restart tor

# tor writes the hostname file once the descriptor is published.
# First-time generation typically takes 5-30 seconds.
HOST_FILE="$HS_DIR/hostname"
deadline=$(( $(date +%s) + 120 ))
while (( $(date +%s) < deadline )); do
    if [[ -f "$HOST_FILE" ]]; then
        break
    fi
    sleep 2
done

[[ -f "$HOST_FILE" ]] || die "tor never wrote $HOST_FILE — check: journalctl -u tor"
ONION=$(cat "$HOST_FILE")
[[ "$ONION" =~ \.onion$ ]] || die "unexpected hostname format: $ONION"
ok ".onion: $ONION"

# ----------------------------------------------------------------------------
log "Writing nginx snippets"
# ----------------------------------------------------------------------------
mkdir -p "$NGINX_SNIPPETS"

# Snippet 1 — Onion-Location header to be included in the clearnet server block.
# Tor Browser sees this header and offers to auto-promote the user to the
# .onion version. Compatible with the spec at:
# https://community.torproject.org/onion-services/advanced/onion-location/
cat > "$NGINX_SNIPPETS/0trust-onion-location.conf" <<EOF
# Generated by tor/scripts/bootstrap.sh
# Include this from the clearnet server block to enable Tor Browser
# auto-promotion to the .onion mirror.
add_header Onion-Location "http://$ONION\$request_uri" always;
EOF

# Snippet 2 — the .onion-serving server block. Goes alongside 0trustvpn.com.conf.
cat > "$NGINX_SNIPPETS/0trust-onion-server.conf" <<EOF
# Generated by tor/scripts/bootstrap.sh
# Onion-side nginx server block. Tor terminates the encryption at the
# rendezvous point and proxies plaintext HTTP to us on 127.0.0.1:$ONION_LOCAL_PORT.
# DO NOT bind this on any other interface.

server {
    listen 127.0.0.1:$ONION_LOCAL_PORT;
    server_name $ONION;

    root /var/www/0trust;
    index index.html;

    # Anonymized access log so we don't write Tor circuit info anywhere
    access_log /var/log/nginx/0trust-onion-access.log anon buffer=32k flush=5s;
    error_log  /var/log/nginx/0trust-onion-error.log warn;

    # Same security headers as clearnet, MINUS HSTS (HTTPS isn't used here,
    # and HSTS on plaintext-over-Tor would be a no-op anyway). CSP keeps
    # the onion isolated to its own origin.
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "no-referrer" always;
    add_header Permissions-Policy "geolocation=(), microphone=(), camera=(), payment=()" always;
    add_header Content-Security-Policy "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'" always;

    # No Onion-Location loop on the onion itself
    # (only the clearnet site sends that header).

    # Static pages with friendly URLs
    location = /             { try_files /index.html =404; }
    location = /status       { try_files /status.html =404; }
    location = /download     { try_files /download.html =404; }
    location = /help         { try_files /help.html =404; }
    location = /audit        { try_files /audit.html =404; }
    location = /security-policy { try_files /security-policy.html =404; }

    # Canary
    location = /canary.txt {
        add_header Content-Type "text/plain; charset=utf-8" always;
        add_header Cache-Control "no-store" always;
    }
    location = /canary.txt.sig {
        add_header Content-Type "text/plain; charset=utf-8" always;
    }
    location = /pubkey.asc {
        add_header Content-Type "application/pgp-keys; charset=utf-8" always;
    }
    location /canary/archive/ {
        add_header Content-Type "text/plain; charset=utf-8" always;
    }

    # Vendored JS
    location /vendor/ {
        add_header Cache-Control "public, max-age=31536000, immutable" always;
    }

    # Release binaries — same path layout as clearnet
    location /releases/ {
        add_header Cache-Control "public, max-age=86400" always;
        location ~ /releases/.*/0trust-[^/]*\$ {
            add_header Content-Type "application/octet-stream" always;
            add_header Content-Disposition "attachment" always;
        }
    }

    # Verify-release script downloadable via curl
    location = /verify-release.sh {
        add_header Content-Type "text/plain; charset=utf-8" always;
    }

    # IMPORTANT: We deliberately do NOT proxy /api/v1 to the control plane
    # over the onion. Customer API traffic stays on clearnet over TLS where
    # the rate-limiting + cert pinning protections apply. The onion is for
    # browsing only.
    location /api/ {
        return 410;  # gone / not provided here
    }

    # 404 / 50x
    error_page 404 /404.html;
    error_page 500 502 503 504 /50x.html;
}
EOF

# ----------------------------------------------------------------------------
log "Activating snippets in main nginx config"
# ----------------------------------------------------------------------------
MAIN_CONF="${NGINX_MAIN_CONF:-/etc/nginx/sites-enabled/0trustvpn.com}"

if [[ -f "$MAIN_CONF" ]]; then
    # 1. Add the include for the onion server block. Safe to repeat the check
    #    so this is idempotent.
    if ! grep -qF "0trust-onion-server.conf" "$MAIN_CONF"; then
        # Append at the end of the file, after the last `}`
        printf "\n# Tor onion mirror (added by tor/scripts/bootstrap.sh)\ninclude %s/0trust-onion-server.conf;\n" \
            "$NGINX_SNIPPETS" >> "$MAIN_CONF"
    fi
    # 2. Inject the Onion-Location header into the main 443 server block.
    #    We look for the first `server_name 0trustvpn.com` line and add an
    #    include directly after it. If it's already there, skip.
    if ! grep -qF "0trust-onion-location.conf" "$MAIN_CONF"; then
        # Use awk because sed-on-multiline is treacherous
        awk -v inc="    include $NGINX_SNIPPETS/0trust-onion-location.conf;" '
          /server_name 0trustvpn.com/ && !done {
            print
            print inc
            done = 1
            next
          }
          { print }
        ' "$MAIN_CONF" > "$MAIN_CONF.new" && mv "$MAIN_CONF.new" "$MAIN_CONF"
    fi
else
    log "  $MAIN_CONF not found — snippets are in $NGINX_SNIPPETS but you'll"
    log "  need to include them manually in your nginx config:"
    log "    include $NGINX_SNIPPETS/0trust-onion-server.conf;"
fi

# ----------------------------------------------------------------------------
log "Reloading nginx"
# ----------------------------------------------------------------------------
nginx -t || die "nginx config test failed — review and fix before continuing"
systemctl reload nginx

# ----------------------------------------------------------------------------
log "Verifying onion is reachable through tor"
# ----------------------------------------------------------------------------
# Use the tor SOCKS proxy on 127.0.0.1:9050 (default) to fetch the onion.
sleep 5  # let descriptors propagate
if curl --socks5-hostname 127.0.0.1:9050 -fsS -m 30 "http://$ONION/" -o /dev/null; then
    ok "onion is reachable through tor"
else
    log "  (couldn't reach onion through tor yet; descriptors typically need"
    log "   60-180 seconds to propagate after first start. Try again:)"
    log "  curl --socks5-hostname 127.0.0.1:9050 http://$ONION/"
fi

cat <<EOF

================================================================
  Tor onion mirror deployed.

  .onion address:
    $ONION

  PUBLISH THIS WIDELY:
    - Add it to your landing page footer (web/index.html)
    - Add it to web/help.html under "How do I contact you?"
    - Sign it with the warrant canary so observers can verify
    - Post it to your Mastodon, Bluesky, project README, etc.

  Tor Browser users on https://0trustvpn.com/ will now see a "purple onion"
  in the address bar (auto-promotion via the Onion-Location header).

  CRITICAL — back up the hidden service private key:
    $HS_DIR/hs_ed25519_secret_key

  Without that backup, a host loss = new .onion address. Customers who
  bookmarked the old address won't find you.

  Suggested backup:
    age -r age1... -o onion-backup.age $HS_DIR/hs_ed25519_secret_key
  Store the encrypted file off-host.

  Future verification:
    curl --socks5-hostname 127.0.0.1:9050 http://$ONION/
================================================================
EOF
