#!/usr/bin/env bash
# ============================================================================
# 0trust control-channel onion
# ============================================================================
# A SECOND onion service, entirely separate from the public browsing mirror in
# bootstrap.sh, that exists for one purpose: to give mesh nodes somewhere to
# fetch their peer list from that is not a fixed address every node connects
# to in the clear.
#
# The problem it solves
# --------------------
# meshd jitters its poll interval (ZTV_POLL_JITTER), which hides the CADENCE
# of the check-in. It does nothing about the DESTINATION. Every node opens a
# regular connection to the same control-plane IP, so anyone able to watch two
# nodes' uplinks — a hosting provider that happens to have two of them, an
# adversary sampling netflow at scale — can group the boxes into one system
# without decrypting anything. Tor removes the shared destination: each node
# reaches its own guard, and the real endpoint lives inside the circuit.
#
# What makes this different from the public onion
# -----------------------------------------------
#   NOT PUBLISHED.  The address is never printed on the website. It is written
#                   into each node's meshd env and nowhere else.
#   CLIENT AUTHED.  v3 client authorization: a party who learns the address
#                   still cannot complete a descriptor fetch without a key we
#                   issued. This is the property the public onion cannot have.
#   ALLOWLISTED.    It maps to an nginx block that proxies exactly the four
#                   node endpoints. bootstrap.sh deliberately keeps /api off
#                   the public onion; this does not undo that decision, it
#                   carves out the node subset behind a separate authenticated
#                   address.
#
# What it does NOT do
# -------------------
# It does not make WireGuard undetectable. Customer tunnels still run plain
# WireGuard to the node's public IP on udp/51820 (or 443), and DPI identifies
# that on sight. This hides the control plane's relationship to its nodes,
# nothing more. Do not let any copy imply otherwise.
#
# Usage:
#   sudo ./tor/scripts/control-onion.sh              # set up + issue 3 keys
#   sudo ./tor/scripts/control-onion.sh --clients 5  # issue 5
# ============================================================================
set -euo pipefail

log()  { printf '\033[1;33m[+] %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m[✓] %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m[!] %s\033[0m\n' "$*" >&2; exit 1; }

CLIENTS=3
DRY_RUN=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --clients) CLIENTS="${2:?}"; shift 2 ;;
        --dry-run) DRY_RUN=1; shift ;;
        *) die "unknown flag: $1" ;;
    esac
done
[[ "$CLIENTS" =~ ^[0-9]+$ ]] && (( CLIENTS >= 1 )) || die "--clients must be a positive integer"

HS_DIR="${ZTV_CONTROL_HS_DIR:-/var/lib/tor/0trust-control}"
TORRC_D="${ZTV_TORRC_D:-/etc/tor/torrc.d}"
NGINX_SNIPPETS="${ZTV_NGINX_SNIPPETS:-/etc/nginx/snippets}"
OUT_DIR="${ZTV_CONTROL_OUT:-/etc/0trust/control-onion}"
CONTROL_LOCAL_PORT="${ZTV_CONTROL_LOCAL_PORT:-8091}"
API_UPSTREAM="${ZTV_API_UPSTREAM:-127.0.0.1:8080}"

# --- The nginx block the onion maps to --------------------------------------
# An allowlist, not a proxy_pass of /api. A node needs four endpoints; nothing
# else on the control plane should be reachable through this address, and
# certainly not the admin surface or the customer account routes.
render_nginx_block() {
    cat <<EOF
# Generated by tor/scripts/control-onion.sh — the mesh control channel.
# Reachable ONLY from the control onion; it listens on loopback and tor is the
# only thing pointed at it.
server {
    listen 127.0.0.1:${CONTROL_LOCAL_PORT};
    server_name _;

    access_log /var/log/nginx/0trust-access.log anon buffer=32k flush=5s;
    error_log  /var/log/nginx/0trust-error.log warn;
    server_tokens off;

    # Nodes send JSON and receive JSON. Nothing here serves a browser, so the
    # whole static/site surface is simply absent.
    location = /api/v1/wg/peers      { proxy_pass http://${API_UPSTREAM}; }
    location = /api/v1/wg/forwards   { proxy_pass http://${API_UPSTREAM}; }
    location = /api/v1/node/heartbeat { proxy_pass http://${API_UPSTREAM}; }
    location = /api/v1/node/provision { proxy_pass http://${API_UPSTREAM}; }

    # Everything else, including the admin dashboard and every customer route,
    # is not merely unproxied — it does not exist at this address.
    location / { return 404; }
}
EOF
}

# --- v3 client authorization keypair ----------------------------------------
# Tor wants base32 of the raw 32-byte x25519 key, padding stripped. openssl
# emits PEM/DER, so the last 32 bytes of the DER body are the raw key.
gen_client_keypair() {
    local tmp; tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' RETURN
    openssl genpkey -algorithm x25519 -out "$tmp/k.pem" 2>/dev/null \
        || die "openssl could not generate an x25519 key"
    local priv pub
    priv="$(grep -v 'PRIVATE KEY' "$tmp/k.pem" | base64 -d | tail -c 32 | base32 | tr -d '=')"
    pub="$(openssl pkey -in "$tmp/k.pem" -pubout 2>/dev/null \
           | grep -v 'PUBLIC KEY' | base64 -d | tail -c 32 | base32 | tr -d '=')"
    [[ ${#priv} -eq 52 && ${#pub} -eq 52 ]] \
        || die "generated key was not 52 base32 chars (priv=${#priv} pub=${#pub})"
    printf '%s %s\n' "$priv" "$pub"
}

if (( DRY_RUN )); then
    log "dry run: rendering the nginx block and one keypair, changing nothing"
    render_nginx_block
    echo
    read -r p q <<<"$(gen_client_keypair)"
    echo "sample client auth  private=${p:0:8}… public=${q:0:8}… (52 chars each)"
    exit 0
fi

[[ $EUID -eq 0 ]] || die "run as root"
command -v tor >/dev/null     || die "tor not installed — run tor/scripts/bootstrap.sh first"
command -v nginx >/dev/null   || die "nginx not installed"
command -v openssl >/dev/null || die "openssl not installed"
command -v base32 >/dev/null  || die "base32 (coreutils) not installed"

log "Creating the hidden service directory"
mkdir -p "$HS_DIR" "$TORRC_D" "$NGINX_SNIPPETS" "$OUT_DIR" "$HS_DIR/authorized_clients"
chown -R debian-tor:debian-tor "$HS_DIR" 2>/dev/null || chown -R tor:tor "$HS_DIR"
chmod 700 "$HS_DIR"
chmod 700 "$OUT_DIR"

log "Issuing $CLIENTS client-authorization keypair(s)"
: > "$OUT_DIR/clients.txt"
chmod 600 "$OUT_DIR/clients.txt"
for i in $(seq 1 "$CLIENTS"); do
    read -r priv pub <<<"$(gen_client_keypair)"
    # Server side: the public half authorises the client.
    printf 'descriptor:x25519:%s\n' "$pub" > "$HS_DIR/authorized_clients/node$i.auth"
    # Operator side: the private half goes on the node, and only there.
    printf 'node%s %s\n' "$i" "$priv" >> "$OUT_DIR/clients.txt"
done
chown -R debian-tor:debian-tor "$HS_DIR/authorized_clients" 2>/dev/null || true
chmod 600 "$HS_DIR/authorized_clients"/*.auth

log "Writing the torrc drop-in"
cat > "$TORRC_D/0trust-control.conf" <<EOF
# 0trust mesh control channel. Separate from the public browsing onion.
HiddenServiceDir $HS_DIR
HiddenServicePort 80 127.0.0.1:$CONTROL_LOCAL_PORT
# v3 client authorization is enforced by the presence of authorized_clients/.
HiddenServiceVersion 3
EOF
grep -q "^%include $TORRC_D" /etc/tor/torrc 2>/dev/null \
    || echo "%include $TORRC_D" >> /etc/tor/torrc

log "Writing the nginx control block"
render_nginx_block > "$NGINX_SNIPPETS/0trust-control-onion.conf"
ln -sf "$NGINX_SNIPPETS/0trust-control-onion.conf" \
       /etc/nginx/sites-enabled/0trust-control-onion 2>/dev/null || true
nginx -t || die "nginx rejected the control block"
systemctl reload nginx

log "Restarting tor and waiting for the address"
systemctl restart tor
for _ in $(seq 1 60); do
    [[ -f "$HS_DIR/hostname" ]] && break
    sleep 1
done
[[ -f "$HS_DIR/hostname" ]] || die "tor did not create $HS_DIR/hostname"
ONION="$(cat "$HS_DIR/hostname")"

ok "control onion: $ONION"
cat <<EOF

================================================================
  The control channel is up. It is NOT published anywhere — this
  address belongs in each node's meshd env and nowhere else.

  On each mesh node:

    1. Install tor and give it the client key for that node
       (one line per node in $OUT_DIR/clients.txt):

         mkdir -p /var/lib/tor/onion_auth && chmod 700 /var/lib/tor/onion_auth
         echo "${ONION%.onion}:descriptor:x25519:<PRIVATE-FROM-clients.txt>" \\
           > /var/lib/tor/onion_auth/0trust.auth_private
         echo "ClientOnionAuthDir /var/lib/tor/onion_auth" >> /etc/tor/torrc
         systemctl restart tor

    2. Point meshd at the onion, through the local SOCKS port:

         CONTROL_URL=http://$ONION
         ZTV_CONTROL_PROXY=127.0.0.1:9050

       meshd resolves the name through the proxy, so the .onion never
       touches the node's resolver. If tor is down the node stops
       syncing rather than falling back to a direct connection — that
       is deliberate, and the control plane will show it going stale.

  Keep $OUT_DIR/clients.txt out of the repository and off the nodes
  except for the one line each node needs.
================================================================
EOF
